// Keep the goal separate from the fixed editorial voice and the learner's
// prerequisite knowledge. User text stays in the structured request context.
export function learningGoalPrompt(settings, action) {
  const common = `学习目标约束 learning-goal-v1：learningIntent 是用户对本次资料提出的明确学习任务，必须落实到正文，不是可忽略的背景标签。围绕目标中的问题、能力要求与学习用途选择解释重点和展开深度；learner 只帮助判断达到这个目标还需要补哪些前提，固定文风不随目标或知识画像改变。
默认目标“看懂这篇文章”只要求解释到足以读懂原文，不自动升级为独立复现、应用练习、延伸专题或超出理解原文所需的额外推导。只有用户明确提出更具体的要求时才增加相应内容。
目标必须在当前 source、chapterBoundary、segment 和授权编辑范围内落实。不能借目标删去原文的实质内容、公式、数据与限定条件，不能编造材料没有支持的结论。当前片段与目标没有直接关系时按其本来作用处理，不牵强附会；目标超出材料能支持的范围时在相关位置说明边界，不假装已达成。
本次 instruction 对局部任务的明确要求优先于泛化目标，但不扩张编辑范围；学习目标不改变 JSON 结构、引用规则和事实标准。输出前核对：与目标相关的关键关系是否解释到位、局部细节是否回到目标问题、是否遗漏必要条件。不要输出计划、自检清单或机械重复“为了满足学习目标”。`;
  if (action === 'generate') return common + (settings.mode === 'translation'
    ? '\n纯翻译的约束：目标只用于术语消歧和理解语境，仍须完整、忠实、按原文顺序翻译；不能因目标加入教学解释、概括替代正文或省略内容。不使用个人知识库。需要按目标展开教学时应使用适应学习。'
    : '\n适应学习的约束：先把目标落实为当前章节可支持的具体理解要求，并在连贯正文中完成它。目标要求推导时，展开关键等式的依据、假设和结论如何回应原问题；目标要求理解或应用时，解释机制、判断依据和适用边界，必要时给出有依据的例子。目标相关处充分展开，其他必要内容紧凑衔接，保留原文实质；不另设目标、背景或原理栏目，不只在开头提一次目标。');
  if (action === 'explain') return common + '\n小纸条的约束：回答选区或光标处的具体疑问，补足它与学习目标之间缺失的概念或推理，并自然说明这一细节在当前问题中的作用；不能把一次追问扩写为整章重讲。';
  if (action === 'rewrite') return common + '\n改写的约束：只在 selection 内提高目标相关表达的清晰度，保留事实、公式和条件，不在选区外追补内容，也不能为了目标把原意改成别的论点。';
  return common + '\n段落编辑的约束：在 editableBlocks 范围内使目标相关的关系和推理更清楚，保持统一文风及原有事实，不增删、移动段落，不改变个人小纸条的含义。';
}
