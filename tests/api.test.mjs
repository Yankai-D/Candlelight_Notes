import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { createDemo } from '../src/demo.ts';
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import { startTestServer } from './support/server.mjs';
import { join } from 'node:path';
import { organizationInput } from '../shared/study-tree.mjs';
import { freshCourseSample } from '../shared/course-style.mjs';
import { freshTemplateLibrary, templateSnapshot } from '../shared/writing-templates.mjs';
import { templateRoutingRequest } from '../shared/template-routing.mjs';

test('local server round trip: config, authenticated requests, mock upstream, origin defense and key removal', { timeout: 60000 }, async () => {
  let upstreamBody;
  const upstream = createServer(async (req, res) => {
    let body = ''; for await (const chunk of req) body += chunk;
    upstreamBody = JSON.parse(body);
    res.setHeader('Content-Type', 'application/json');
    const organizing = upstreamBody.messages[0].content.includes('folder-topics-v2');
    const styling = upstreamBody.messages[0].content.includes('course-style-edit-v1');
    const templateStyling = upstreamBody.messages[0].content.includes('template-sample-v1');
    const routing = upstreamBody.messages[0].content.includes('template-routing-v2');
    const styleData = styling || templateStyling ? JSON.parse(upstreamBody.messages[1].content) : null;
    const documents = organizing ? JSON.parse(upstreamBody.messages[1].content).documents : [];
    const result = routing ? { task: 'understand', material: 'course', fit: 'direct', adaptation: '', templateId: 'lecture', reason: '按知识点组织的教学资料。' } : styling || templateStyling ? { rules: ['用完整因果关系衔接段落。'], edits: [{ id: styleData.paragraphs[0].id, text: styleData.paragraphs[0].text + '中心需要与离散程度结合解释。' }] }
      : organizing ? { groups: [{ label: '测试主题', description: '', documents: documents.map(d => d.ref) }] }
      : { title: '接口测试纸条', paragraphs: ['这是一条模拟模型返回，仅供测试。'], sourcePages: [2], summary: '接口链路通过' };
    res.end(JSON.stringify({ choices: [{ finish_reason: 'stop', message: { content: JSON.stringify(result) } }] }));
  });
  upstream.listen(0, '127.0.0.1'); await once(upstream, 'listening');
  const upstreamPort = upstream.address().port;
  let server;
  try {
  server=await startTestServer({DEEPSEEK_BASE_URL:`http://127.0.0.1:${upstreamPort}`,DEEPSEEK_MODEL:'test-model'});
  const libraryDir = join(server.directory,'library');
  const libraryDocument = { ...createDemo(), id: 'paper-fixture', demo: false, library: { id: 'fixture', label: 'Fixture', group: 'Test', authors: 'Author', year: '2020', order: 0 } };
  await writeFile(join(libraryDir, 'catalog.json'), JSON.stringify({ collection: 'Test library', documents: [libraryDocument] }));
  await copyFile('public/attention-field-notes.pdf', join(libraryDir, 'fixture.pdf'));
    const base = server.base;
    const coursePreview = await fetch(base + '/review/course.html');
    assert.equal(coursePreview.status, 200);
    assert.match(await coursePreview.text(), /course-lecture-v1/);
    const initial = await (await fetch(base + '/api/config')).json();
    const library = await (await fetch(base + '/api/library')).json();
    assert.equal(library.documents.length, 1);
    const source = await fetch(base + '/api/library/fixture/source');
    assert.equal(source.headers.get('content-type'), 'application/pdf');
    assert.deepEqual(Buffer.from(await source.arrayBuffer()), await readFile('public/attention-field-notes.pdf'));
    assert.equal((await fetch(base + '/api/library/not-listed/source')).status, 404);
    assert.equal((await fetch(base + '/api/library/%2e%2e%2fsecret/source')).status, 404);
    assert.equal((await fetch(base + '/api/library', { headers: { Origin: 'https://untrusted.example' } })).status, 403);
    assert.equal(initial.configured, false);
    assert.equal(initial.apiKey, undefined);
    const blocked = await fetch(base + '/api/config', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
    assert.equal(blocked.status, 403);
    const foreign = await fetch(base + '/api/config', { headers: { Origin: 'https://untrusted.example' } });
    assert.equal(foreign.status, 403);
    const headers = { 'Content-Type': 'application/json', 'X-Reading-Tree-Token': initial.token };
    const idealList = await fetch(base + '/api/edit', { method: 'POST', headers, body: JSON.stringify({ action: 'ideal-tree', command: 'list', workspaceToken: initial.workspaceToken }) });
    assert.equal(idealList.status, 200); assert.deepEqual((await idealList.json()).result.trees, []);
    assert.equal((await fetch(base + '/api/edit', { method: 'POST', body: JSON.stringify({ action: 'ideal-tree', command: 'list' }) })).status, 403);
    const settings = await fetch(base + '/api/config', { method: 'POST', headers, body: JSON.stringify({ baseUrl: `http://127.0.0.1:${upstreamPort}`, model: 'test-model', apiKey: 'not-a-real-key' }) });
    assert.equal(settings.status, 200);
    assert.equal((await settings.json()).configured, true);
    const sample = freshCourseSample();
    const styledSample = await fetch(base + '/api/edit', { method: 'POST', headers, body: JSON.stringify({ action: 'course-style', revision: 3, instruction: '衔接更自然。', sample, workspaceToken: initial.workspaceToken }) });
    assert.equal(styledSample.status, 200);
    const sampleReply = (await styledSample.json()).result;
    assert.equal(sampleReply.revision, 3);
    assert.equal(sampleReply.rendering.format, 'reading-tree-note-v1');
    assert.notEqual(sampleReply.paragraphs[0].text, sample.paragraphs[0].text);
    assert.equal(JSON.parse(upstreamBody.messages[1].content).learner, undefined);
    const doc = createDemo();
    const route = await fetch(base + '/api/edit', { method: 'POST', headers, body: JSON.stringify({ ...templateRoutingRequest(doc, freshTemplateLibrary()), workspaceToken: initial.workspaceToken }) });
    assert.equal(route.status, 200); assert.equal((await route.json()).result.templateId, 'lecture');
    const templateEdit = await fetch(base + '/api/edit', { method: 'POST', headers, body: JSON.stringify({ action: 'template-style', revision: 1, instruction: '分工更清楚', template: templateSnapshot(freshTemplateLibrary(), 'lecture'), workspaceToken: initial.workspaceToken }) });
    assert.equal(templateEdit.status, 200); assert.equal((await templateEdit.json()).result.revision, 1);
    const edit = await fetch(base + '/api/edit', { method: 'POST', headers, body: JSON.stringify({ action: 'explain', scope: 'selection', instruction: '解释当前段落', revision: 0, chapterId: doc.chapters[1].id, anchorId: doc.chapters[1].content.content[0].attrs.id, document: doc }) });
    assert.equal(edit.status, 200);
    const reply = await edit.json();
    assert.equal(reply.result.title, '接口测试纸条');
    assert.equal(reply.result.rendering.format, 'reading-tree-note-v1');
    assert.equal(reply.result.rendering.blocks[0].type, 'paragraph');
    assert.equal(upstreamBody.model, 'test-model');
    assert.deepEqual(JSON.parse(upstreamBody.messages[1].content).source.map(p => p.number), [2, 3]);
    assert.equal(JSON.parse(upstreamBody.messages[1].content).learningIntent, doc.intent);
    assert.deepEqual(JSON.parse(upstreamBody.messages[1].content).learning, { mode: 'adaptive', template: 'guided-v3' });
    assert.match(upstreamBody.messages[0].content, /学习目标约束 learning-goal-v2/);
    assert.match(upstreamBody.messages[0].content, /小纸条的约束/);
    assert.equal((await fetch(base + '/api/organize', { method: 'POST', body: '{}' })).status, 403);
    assert.equal((await fetch(base + '/api/organize', { method: 'POST', headers, body: JSON.stringify({ ...organizationInput([doc]), instruction: 'extra prompt' }) })).status, 400);
    const organized = await fetch(base + '/api/organize', { method: 'POST', headers, body: JSON.stringify(organizationInput([doc])) });
    assert.equal(organized.status, 200);
    const indexed = await organized.json();
    assert.deepEqual(indexed.result.branches[0].documentIds, [doc.id]);
    assert.deepEqual(indexed.result.documents[0].concepts, []);
    assert.equal(indexed.model, 'test-model');
    assert.equal(JSON.parse(upstreamBody.messages[1].content).knowledge, undefined);
    const remove = await fetch(base + '/api/config', { method: 'POST', headers, body: JSON.stringify({ baseUrl: `http://127.0.0.1:${upstreamPort}`, model: 'test-model', apiKey: '' }) });
    assert.equal((await remove.json()).configured, false);
    assert.equal((await fetch(base + '/api/test', { method: 'POST', headers, body: '{}' })).status, 400);
    const exported = await fetch(base + '/api/export/pdf', { method: 'POST', headers, body: JSON.stringify({ document: doc, fontSize: 17, theme: 'dark' }) });
    assert.equal(exported.status, 200, exported.status === 200 ? '' : await exported.text());
    assert.equal(exported.headers.get('Content-Type'), 'application/pdf');
    const bytes = new Uint8Array(await exported.arrayBuffer());
    assert.equal(new TextDecoder().decode(bytes.slice(0, 5)), '%PDF-');
    assert.equal((await fetch(base + '/api/export/pdf', { method: 'POST', headers, body: JSON.stringify({ document: doc, theme: 'unknown' }) })).status, 400);
    assert.equal((await fetch(base + '/')).status, 200);
  } finally {
    await server?.stop(); upstream.closeAllConnections(); await new Promise(resolve => upstream.close(resolve));
  }
});
